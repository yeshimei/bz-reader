/* ============================================================
 * bz-reader · 支持者名单（src/data/reward.ts）
 *
 * 「支持作者」弹窗里那份名单，以及它的日期格式化。为什么是常量：
 * 微信赞赏码没有可查的接口，谁给了、写了什么只有作者看得到，只能手动维护。
 *
 * **这份名单在 bz 插件里也有一份**（`bz/src/core/reward-names.ts`）。
 * 两边是同一个作者、同一张赞赏码，名单内容必须一致——新记一位时两处都要加，
 * 顺序都是**时间倒序**（最新的在前），序号由长度倒推（最新一位是最大号）。
 * 记名单的流程见 skill `bz-reward`：它已经写明「两处一起改」。
 *
 * 金额位两种写法：
 *   · 数字：微信赞赏码收到的金额（元，整数），纸面上显示 `¥12`；
 *   · `'patron'`：不走赞赏码的那条路（在赞助商店买了东西），
 *     显示成「赞助人」——文案走语言包，不在这里写死。
 *
 * 这个文件被 tests/no-hardcoded-zh.test.ts 豁免：昵称与留言是**数据**，
 * 不是界面文案，不进语言包、也不该随界面语言翻译。
 * ============================================================ */

/** 一条留名记录 */
export interface RewardName {
  /** 昵称（赞赏时填的，原样显示） */
  name: string;
  /**
   * 金额位。
   *  - 数字：微信赞赏码收到的金额（元，按实际收到的记，3.14 就是 3.14）；
   *  - `'patron'`：不在赞赏码这条路（赞助商店买了东西），显示「赞助人」。
   */
  amount: number | 'patron';
  /** 日期 `YYYY-MM-DD` */
  date: string;
  /** 留言（可空；空的就只显示名字那一行，不留占位文字） */
  message?: string;
}

